"""Сверка симулированной прибыли с реально полученной on-chain — баланс
token_in ДО отправки минус баланс ПОСЛЕ подтверждения включения. Балансовый
снимок, не индивидуальный трейс Transfer-событий — тот же принцип, что и
DEX-агностичный wallet_watcher.py на Solana: чтобы узнать эффект на баланс,
не нужно декодировать конкретный DEX.

Не участвует в решении о входе (кэпы/drawdown остаются на expected_profit —
реализованное число доступно только ПОСЛЕ того, как решение уже принято и
исполнено) — это постфактум-аудит точности симуляции поверх trade_log.py,
не отдельный источник правды для риск-контроля.

ponytail: не защищено от гонок с остальной активностью того же кошелька в
промежутке между "до" и "после" — для однопроцессного бота, который держит
отдельный кошелёк на стратегию (см. README про раздельные кошельки), это
приемлемо; апгрейд — трейс конкретных Transfer-логов транзакции, если
когда-нибудь появится не-эксклюзивная активность на этом кошельке.
"""


def realized_profit_from_balances(balance_before: int, balance_after: int) -> int:
    """Чистая реализованная разница в единицах token_in. Не включает
    уплаченный газ, если token_in не сам нативный токен сети — газ всегда
    списывается из нативного баланса отдельно, см. gas_cost_wei_from_receipt."""
    return balance_after - balance_before


def gas_cost_wei_from_receipt(receipt: dict) -> int:
    """Фактически уплаченный газ по receipt транзакции (EIP-1559:
    gasUsed * effectiveGasPrice)."""
    return receipt.get("gasUsed", 0) * receipt.get("effectiveGasPrice", 0)
